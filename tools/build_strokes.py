#!/usr/bin/env python3
"""Builds js/kana-strokes.js, the stroke data Kana Brush draws and checks against.

The strokes come from KanjiVG (https://kanjivg.tagaini.net), (c) Ulrich Apel and contributors, CC BY-SA 3.0, which
Settings credits. Every single kana taught in the Reading Dojo (js/dojo-data.js) gets its strokes, in order, as SVG
path data in KanjiVG's 109x109 box, plus where KanjiVG puts each stroke's number.

    python3 tools/build_strokes.py                 # downloads the few files it needs from KanjiVG on GitHub
    KANJIVG_DIR=/path/to/kanjivg python3 tools/build_strokes.py   # or reads a local checkout (its kanji/ folder)

The app itself never fetches anything: the generated file ships in the repo. Re-run only when the Dojo's kana change,
then bump CACHE_VERSION in sw.js.
"""
import json
import os
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'js' / 'kana-strokes.js'
RAW = 'https://raw.githubusercontent.com/KanjiVG/kanjivg/master/kanji/{}.svg'


def dojo_kana():
    src = (ROOT / 'js' / 'dojo-data.js').read_text(encoding='utf8')
    seen = []
    for k in re.findall(r"C\('([^']+)'", src):
        if len(k) == 1 and k not in seen:
            seen.append(k)
    return seen


def svg_for(ch):
    name = format(ord(ch), '05x')
    local = os.environ.get('KANJIVG_DIR')
    if local:
        return (Path(local) / 'kanji' / f'{name}.svg').read_text(encoding='utf8')
    with urllib.request.urlopen(RAW.format(name), timeout=30) as r:
        return r.read().decode('utf8')


def strokes_of(ch, svg):
    paths = re.findall(r'<path id="kvg:[0-9a-f]+-s(\d+)"[^>]*?\sd="([^"]+)"', svg)
    paths.sort(key=lambda p: int(p[0]))
    nums = [tuple(float(v) for v in m) for m in re.findall(r'matrix\(1 0 0 1 ([\d.]+) ([\d.]+)\)', svg)]
    if not paths:
        sys.exit(f'No strokes found for {ch}')
    out = []
    for i, (_, d) in enumerate(paths):
        x, y = nums[i] if i < len(nums) else (0, 0)
        out.append([re.sub(r'\s+', ' ', d.strip()), round(x, 1), round(y, 1)])
    return out


def main():
    data = {}
    for ch in dojo_kana():
        data[ch] = strokes_of(ch, svg_for(ch))
        print(ch, len(data[ch]), file=sys.stderr)
    lines = [
        '// Generated by tools/build_strokes.py. Do not edit by hand.',
        '// Kana stroke data from KanjiVG (https://kanjivg.tagaini.net), (c) Ulrich Apel and contributors,',
        '// licensed CC BY-SA 3.0 (https://creativecommons.org/licenses/by-sa/3.0/). Credited in Settings.',
        '// kana -> strokes in writing order: [SVG path in a 109x109 box, stroke-number x, stroke-number y].',
        'export const STROKES = {',
    ]
    for ch, strokes in data.items():
        lines.append(f'{json.dumps(ch, ensure_ascii=False)}: {json.dumps(strokes, ensure_ascii=False, separators=(",", ":"))},')
    lines.append('};')
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf8')
    print(f'Wrote {OUT.relative_to(ROOT)}: {len(data)} kana', file=sys.stderr)


if __name__ == '__main__':
    main()

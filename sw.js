self.addEventListener('install', (event) => {
  // App files must all cache; voice clips are cached in batches and a failed clip doesn't block the update.
  const core = FILES.filter((f) => !f.startsWith('./audio/'));
  const clips = FILES.filter((f) => f.startsWith('./audio/'));
  event.waitUntil(
    caches.open(CACHE_VERSION)
      .then(async (cache) => {
        await cache.addAll(core.map((f) => new Request(f, { cache: 'reload' })));
        // Clip names are content hashes, so a clip already cached by an older version is reused, not downloaded again.
        for (let i = 0; i < clips.length; i += 40) {
          await Promise.all(clips.slice(i, i + 40).map(async (f) => {
            const old = await caches.match(f);
            return old ? cache.put(f, old) : cache.add(new Request(f, { cache: 'reload' }));
          }).map((p) => p.catch(() => {})));
        }
      })
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('kotoba-beat-') && k !== CACHE_VERSION).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

// Safari asks for audio in byte ranges and won't play a clip served whole, so answer ranges from the cached file.
async function rangeResponse(req) {
  const url = new URL(req.url);
  url.search = '';
  let full = await caches.match(url.href);
  if (!full) {
    full = await fetch(url.href);
    if (full.ok && full.status === 200) {
      const copy = full.clone();
      caches.open(CACHE_VERSION).then((c) => c.put(url.href, copy));
    } else {
      return full;
    }
  }
  const buf = await full.arrayBuffer();
  const m = /bytes=(\d*)-(\d*)/.exec(req.headers.get('range') || '');
  let start = m && m[1] ? Number(m[1]) : 0;
  let end = m && m[2] ? Number(m[2]) : buf.byteLength - 1;
  if (m && !m[1] && m[2]) { start = Math.max(0, buf.byteLength - Number(m[2])); end = buf.byteLength - 1; }
  end = Math.min(end, buf.byteLength - 1);
  return new Response(buf.slice(start, end + 1), {
    status: 206,
    statusText: 'Partial Content',
    headers: {
      'Content-Type': full.headers.get('Content-Type') || 'audio/mpeg',
      'Content-Range': `bytes ${start}-${end}/${buf.byteLength}`,
      'Content-Length': String(end - start + 1),
      'Accept-Ranges': 'bytes',
    },
  });
}

// Cache first (offline), falling back to the network; navigations fall back to the cached shell.
self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  if (req.headers.has('range')) { event.respondWith(rangeResponse(req).catch(() => fetch(req))); return; }
  event.respondWith(
    caches.match(req, { ignoreSearch: true }).then((hit) => {
      if (hit) return hit;
      return fetch(req).then((res) => {
        if (res.status === 200 && res.type === 'basic') {
          const copy = res.clone();
          caches.open(CACHE_VERSION).then((c) => c.put(req, copy));
        }
        return res;
      }).catch(() => (req.mode === 'navigate' ? caches.match('./index.html') : Response.error()));
    })
  );
});

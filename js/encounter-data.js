// A turn: what they say, what you want to say (in English), the right reply, two wrong replies (a different meaning),
// and sometimes a `tone` reply: the right meaning at the wrong politeness level. A tone reply still counts, and the
// person reacts to it (too casual with shop staff, too stiff with a classmate).

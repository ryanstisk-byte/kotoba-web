/** Every scene, each tagged with its JLPT level, in the order they unlock per person (N5, then N4, then N3). */
export const SCENES = [...tagLevel(N5, 'N5'), ...tagLevel(N4, 'N4'), ...tagLevel(N3, 'N3')];
export const SCENE_BY_ID = Object.fromEntries(SCENES.map((s) => [s.id, s]));

/** The narrator's voice reads every reply, as a model to copy. */
export const REPLY_VOICE = 0;

/** Every voiced line with its voice and level, for tools/collect.mjs. */
export function encounterLines() {
  const out = [];
  for (const s of SCENES) {
    const v = PERSON[s.who].voice;
    for (const t of s.turns) {
      out.push([t.says, v, s.level]);
      out.push([t.reply, REPLY_VOICE, s.level]);
      if (t.tone) out.push([t.tone, REPLY_VOICE, s.level]);
    }
    out.push([s.bye, v, s.level]);
  }
  for (const p of PEOPLE) for (const l of [...p.toneLines, ...p.huhLines]) out.push([l, p.voice, 'N5']);
  return out;
}
